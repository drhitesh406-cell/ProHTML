#!/usr/bin/env python3
"""Embed assets/mcq-tags.json into custom-module.html as INLINE_TAG_INDEX.

HTML Reader opens the maker from a blob: URL (index.html -> URL.createObjectURL),
so a relative `fetch('assets/mcq-tags.json')` cannot resolve. Embedding the
index makes the tag filter work in the Reader, in the preview and offline.

Run this after editing assets/mcq-tags.json to keep both copies in sync.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSET = ROOT / "assets" / "mcq-tags.json"
PAGE = ROOT / "custom-module.html"
BEGIN = "/* BEGIN INLINE MCQ TAG INDEX */"
END = "/* END INLINE MCQ TAG INDEX */"


def main() -> int:
    data = json.loads(ASSET.read_text(encoding="utf-8"))
    if not isinstance(data.get("questions"), dict) or not isinstance(data.get("tags"), list):
        print("assets/mcq-tags.json is missing 'questions' or 'tags'", file=sys.stderr)
        return 1
    compact = json.dumps(data, separators=(",", ":"), sort_keys=True, ensure_ascii=True)
    # Keep the JSON inert inside a <script> element and safe for JS string parsing.
    compact = compact.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    block = (
        BEGIN
        + "\n/* Generated by scripts/embed-mcq-tags.py — edit assets/mcq-tags.json, then rerun. */\n"
        + "/* Inline because HTML Reader loads this page from a blob: URL where relative fetches fail. */\n"
        + "const INLINE_TAG_INDEX=" + compact + ";\n"
        + END
    )
    html = PAGE.read_text(encoding="utf-8")
    i = html.find(BEGIN)
    j = html.find(END)
    if i < 0 or j < 0 or j < i:
        print("marker block not found in custom-module.html", file=sys.stderr)
        return 1
    j += len(END)
    PAGE.write_text(html[:i] + block + html[j:], encoding="utf-8")
    print(
        "embedded %d tagged MCQs (%d bytes) into custom-module.html"
        % (len(data["questions"]), len(compact))
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
